/*
 * Build a runtime opening book from KataGo-analyzed training positions.
 *
 * Input: strat_train*.json (KataGo top moves in real-game positions) + the
 * SGFs they came from (to rebuild prefixes). Output: JS data file with
 * canonical-hash -> KataGo top reply (canonical coords), plus the inverse
 * symmetry table for runtime mapping.
 *
 * Usage: node tools/eval/make_book.js <out.js> <train.json> [...]
 */
'use strict';

const fs = require('fs');
const path = require('path');
const child = require('child_process');

const COLS = 'ABCDEFGHJ';

// Dihedral transforms (must match engine's xf/symApply convention).
function xf(t, r, c) {
    if (t === 0) return [r, c];
    if (t === 1) return [c, 8 - r];
    if (t === 2) return [8 - r, 8 - c];
    if (t === 3) return [8 - c, r];
    if (t === 4) return [8 - r, c];
    if (t === 5) return [r, 8 - c];
    if (t === 6) return [c, r];
    return [8 - c, 8 - r];
}
// Inverse table: INV[t] = s such that xf(s, xf(t, p)) == p.
const INV = (() => {
    const inv = [];
    for (let t = 0; t < 8; t++) {
        for (let s = 0; s < 8; s++) {
            let ok = true;
            for (let r = 0; r < 9 && ok; r++)
                for (let c = 0; c < 9 && ok; c++) {
                    const [r1, c1] = xf(t, r, c);
                    const [r2, c2] = xf(s, r1, c1);
                    if (r2 !== r || c2 !== c) ok = false;
                }
            if (ok) { inv[t] = s; break; }
        }
    }
    return inv;
})();

function canonKey(black, white) {
    let best = null, bestT = 0;
    for (let t = 0; t < 8; t++) {
        const tb = [], tw = [];
        for (const i of black) {
            const [r, c] = xf(t, Math.floor(i / 9), i % 9);
            tb.push(r * 9 + c);
        }
        for (const i of white) {
            const [r, c] = xf(t, Math.floor(i / 9), i % 9);
            tw.push(r * 9 + c);
        }
        tb.sort((a, b) => a - b);
        tw.sort((a, b) => a - b);
        const k = tb.join(',') + '|' + tw.join(',');
        if (best === null || k < best) { best = k; bestT = t; }
    }
    return { key: best, t: bestT };
}

function findSgf(base) {
    const out = child.execSync(`find "${path.join(__dirname, 'sgf')}" -name "${base}"`, { encoding: 'utf8' }).trim();
    return out ? out.split('\n')[0] : null;
}

function parseVertex(v) {
    const c = COLS.indexOf(v[0].toUpperCase());
    return { r: 9 - parseInt(v.slice(1), 10), c };
}

function main() {
    const args = process.argv.slice(2);
    const outJs = args.shift();
    const book = {}; // key -> {turn, r, c, wr} (reply in CANONICAL coords)
    const sgfCache = {};
    let kept = 0, dup = 0;
    for (const trainPath of args) {
        const data = JSON.parse(fs.readFileSync(trainPath, 'utf8'));
        for (const rec of data) {
            const [base, plyStr] = rec.id.split(':');
            const ply = +plyStr;
            if (!sgfCache[base]) {
                const f = findSgf(base);
                if (!f) continue;
                const s = fs.readFileSync(f, 'utf8');
                sgfCache[base] = [...s.matchAll(/;([BW])\[([a-z]{2}|tt)\]/g)].map((m) => ({
                    color: m[1], pass: m[2] === 'tt',
                    r: m[2] === 'tt' ? -1 : 'abcdefghj'.indexOf(m[2][1]),
                    c: m[2] === 'tt' ? -1 : 'abcdefghj'.indexOf(m[2][0]),
                }));
            }
            const seq = sgfCache[base].slice(0, ply);
            if (seq.some((m) => m.pass)) continue;
            if (ply > 24) continue; // opening book range only
            const black = new Set(), white = new Set();
            for (const m of seq) (m.color === 'B' ? black : white).add(m.r * 9 + m.c);
            const { key, t } = canonKey(black, white);
            const top = (rec.top || []).filter((x) => x.move !== 'pass')[0];
            if (!top) continue;
            const v = parseVertex(top.move);
            const [rr, rc] = xf(t, v.r, v.c); // reply -> canonical frame
            if (book[key]) { dup++; continue; }
            book[key] = { turn: rec.turn, r: rr, c: rc, wr: +top.winrate.toFixed(3) };
            kept++;
        }
    }
    const js = '// Auto-generated by tools/eval/make_book.js — DO NOT EDIT.\n' +
        '// KataGo-distilled opening replies: canonical-hash -> [turn, r, c].\n' +
        '// Coordinates are CANONICAL; runtime maps via inverse transform.\n' +
        `var KATAGO_BOOK_INV = [${INV.join(',')}];\n` +
        `var KATAGO_BOOK = ${JSON.stringify(book)};\n`;
    fs.writeFileSync(outJs, js);
    console.log(`book: ${kept} positions kept, ${dup} transposition-dups skipped -> ${outJs} (${fs.statSync(outJs).size} bytes)`);
}

if (require.main === module) main();
module.exports = { xf, INV, canonKey };
